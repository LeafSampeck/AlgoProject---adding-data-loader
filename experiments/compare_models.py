"""
Experiment 1 (classification accuracy) and Experiment 3 (architecture ablation).

Loads each model's best checkpoint, evaluates on the SAME held-out test set,
and writes:
    results/classification_results.csv     one row per model (and per seed)
    results/classification_results.tex     IEEE-ready table for Section VII
    results/predictions_<model>.npz        y_true / y_pred, reused by confusion_matrices.py

With several seeds, the table reports mean ± std across seeds.

Usage (from the repo root):
    python -m experiments.compare_models --data synthetic
    python -m experiments.compare_models --data fi2010 --seeds 42 43 44
"""

import argparse
import csv
import os

import numpy as np

from config import DEFAULT_CONFIG, MODEL_DISPLAY_NAMES
from data.synthetic import get_dataloaders
from experiments.common import (checkpoint_path, compute_metrics, get_device,
                                load_checkpoint, predict)
from models import MODEL_NAMES
from models.common import count_parameters

METRIC_KEYS = ["accuracy", "macro_precision", "macro_recall", "macro_f1"]


def evaluate_all(data_source, seeds, models, out_dir="results"):
    os.makedirs(out_dir, exist_ok=True)
    device = get_device()
    cfg = dict(DEFAULT_CONFIG)
    _, _, test_loader = get_dataloaders(data_source, cfg)

    rows = []
    for name in models:
        for seed in seeds:
            cfg["seed"] = seed
            path = checkpoint_path(name, cfg)
            if not os.path.exists(path):
                print(f"[skip] {name} seed {seed}: no checkpoint at {path}")
                continue
            model, ckpt = load_checkpoint(path, device)
            y_true, y_pred = predict(model, test_loader, device)
            m = compute_metrics(y_true, y_pred)
            rows.append({"model": name, "seed": seed, "params": count_parameters(model),
                         "best_epoch": ckpt["epoch"], **{k: m[k] for k in METRIC_KEYS}})
            np.savez(os.path.join(out_dir, f"predictions_{name}_seed{seed}.npz"),
                     y_true=y_true, y_pred=y_pred)
            print(f"{name:14s} seed {seed}: acc {m['accuracy']:.4f}  macro-F1 {m['macro_f1']:.4f}")
    return rows


def write_csv(rows, path):
    if not rows:
        return
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def summarize(rows):
    """Group by model -> mean/std of each metric across seeds."""
    out = {}
    for name in MODEL_NAMES:
        rs = [r for r in rows if r["model"] == name]
        if not rs:
            continue
        s = {"params": rs[0]["params"], "n_seeds": len(rs)}
        for k in METRIC_KEYS:
            vals = np.array([r[k] for r in rs]) * 100.0      # report as percentages
            s[k] = (vals.mean(), vals.std(ddof=1) if len(vals) > 1 else 0.0)
        out[name] = s
    return out


def write_latex(summary, path, data_source):
    def fmt(mean, std, n):
        return f"{mean:.2f} $\\pm$ {std:.2f}" if n > 1 else f"{mean:.2f}"

    lines = [
        "% Auto-generated by experiments/compare_models.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        f"\\caption{{Test-set classification results on {'FI-2010' if data_source == 'fi2010' else 'SYNTHETIC DATA (do not report)'}"
        f" (horizon $k={DEFAULT_CONFIG['horizon_k']}$). Values in \\%.}}",
        "\\label{tab:classification}",
        "\\begin{tabular}{lcccc}",
        "\\hline",
        "Model & Accuracy & Macro-F1 & Macro-Prec. & Params \\\\",
        "\\hline",
    ]
    best_f1 = max(s["macro_f1"][0] for s in summary.values()) if summary else None
    for name, s in summary.items():
        n = s["n_seeds"]
        f1 = fmt(*s["macro_f1"], n)
        if s["macro_f1"][0] == best_f1:
            f1 = f"\\textbf{{{f1}}}"
        lines.append(f"{MODEL_DISPLAY_NAMES[name]} & {fmt(*s['accuracy'], n)} & {f1} & "
                     f"{fmt(*s['macro_precision'], n)} & {s['params']:,} \\\\")
    lines += ["\\hline", "\\end{tabular}", "\\end{table}"]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", choices=["synthetic", "fi2010"], default="synthetic")
    ap.add_argument("--seeds", nargs="+", type=int, default=[DEFAULT_CONFIG["seed"]])
    ap.add_argument("--models", nargs="+", default=MODEL_NAMES)
    args = ap.parse_args()

    rows = evaluate_all(args.data, args.seeds, args.models)
    if not rows:
        print("No checkpoints found. Train first (see README).")
        return
    write_csv(rows, "results/classification_results.csv")
    summary = summarize(rows)
    write_latex(summary, "results/classification_results.tex", args.data)

    print("\nSummary (mean over seeds, %):")
    for name, s in summary.items():
        print(f"  {MODEL_DISPLAY_NAMES[name]:28s} acc {s['accuracy'][0]:6.2f}  "
              f"macro-F1 {s['macro_f1'][0]:6.2f}  params {s['params']:,}")
    print("\nWrote results/classification_results.csv and .tex")


if __name__ == "__main__":
    main()